CREATE TABLE IF NOT EXISTS app_sleep_logs (
  id                      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  app_user_id             INT NOT NULL,
  date                    DATE NOT NULL,
  sleep_start             DATETIME NULL,
  wake_time               DATETIME NULL,
  duration_minutes        INT NULL,
  time_in_bed_minutes     INT NULL,
  timezone_offset_minutes INT NULL,
  source                  VARCHAR(50) NULL,
  source_name             VARCHAR(100) NULL,
  confidence              FLOAT NULL,
  efficiency_percent      INT NULL,
  awakenings              INT NULL,
  sleep_latency_minutes   INT NULL,
  disturbances            INT NULL,
  stage_awake             INT NULL,
  stage_light             INT NULL,
  stage_deep              INT NULL,
  stage_rem               INT NULL,
  stage_asleep            INT NULL,
  low_motion_signal       TINYINT(1) NOT NULL DEFAULT 0,
  tracking_not_stopped    TINYINT(1) NOT NULL DEFAULT 0,
  sleep_score             INT NULL,
  sleep_quality           VARCHAR(20) NULL,
  created_at              DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at              DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_user_date (app_user_id, date),
  INDEX idx_user_date (app_user_id, date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
